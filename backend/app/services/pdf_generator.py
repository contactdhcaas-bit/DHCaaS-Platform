    def _create_issues_table(self, issues: List[Dict]) -> List:
        """Create professionally formatted issues table"""
        elements = []

        issue_data = [["#", "Severity", "Rule", "Column/Field", "Affected Rows"]]

        for idx, issue in enumerate(issues, 1):
            issue_data.append([
                str(idx),
                issue.get('severity', 'N/A'),
                issue.get('rule_name', issue.get('title', 'N/A')),
                issue.get('column_name', issue.get('datasource', 'N/A')),
                str(issue.get('affected_rows', 'Unknown'))
            ])

        issue_table = Table(issue_data,
                           colWidths=[0.4 * inch, 1 * inch, 2.2 * inch, 1.7 * inch, 1.2 * inch])

        issue_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), self.colors['navy_medium']),
            ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
            ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
            ('FONTSIZE', (0, 0), (-1, 0), 11),
            ('FONTSIZE', (0, 1), (-1, -1), 10),
            ('ALIGN', (0, 0), (0, -1), 'CENTER'),
            ('ALIGN', (1, 0), (-1, -1), 'LEFT'),
            ('ALIGN', (4, 0), (4, -1), 'CENTER'),
            ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
            ('TOPPADDING', (0, 0), (-1, -1), 10),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 10),
            ('LEFTPADDING', (0, 0), (-1, -1), 10),
            ('RIGHTPADDING', (0, 0), (-1, -1), 10),
            ('LINEBELOW', (0, 0), (-1, 0), 2, self.colors['brand_primary']),
            ('GRID', (0, 1), (-1, -1), 0.5, self.colors['border']),
        ]))

        # Apply severity-based row colors
        for i, issue in enumerate(issues, 1):
            severity = issue.get('severity', '').lower()
            if severity == 'critical':
                bg_color = colors.HexColor('#FEE2E2')
            elif severity == 'high':
                bg_color = colors.HexColor('#FEF3C7')
            else:
                bg_color = colors.white

            issue_table.setStyle(TableStyle([
                ('BACKGROUND', (0, i), (-1, i), bg_color)
            ]))

        elements.append(issue_table)
        return elements

