    def generate_report(self, report_data: Dict[str, Any], output_path: str) -> str:
        """Generate complete enterprise PDF report"""
        doc = SimpleDocTemplate(
            output_path,
            pagesize=letter,
            rightMargin=0.75 * inch,
            leftMargin=0.75 * inch,
            topMargin=1 * inch,
            bottomMargin=1 * inch,
            title=f"DHCaaS Data Quality Report - {report_data.get('datasource_name', 'Report')}",
            author="DHCaaS Platform",
            subject="Data Quality Assessment Report"
        )

        story = []
        story.extend(self.create_executive_summary_page(report_data))
        story.extend(self.create_data_profile_section(report_data))
        story.extend(self.create_issues_section(report_data))
        story.extend(self.create_recommendations_section(report_data))

        def on_first_page(canvas_obj, doc):
            self.create_cover_page(canvas_obj, letter[0], letter[1], report_data)

        def on_later_pages(canvas_obj, doc):
            canvas_obj.saveState()
            canvas_obj.setFont('Helvetica', 9)
            canvas_obj.setFillColor(self.colors['text_secondary'])
            
            datasource = report_data.get('datasource_name', 'N/A')
            if len(datasource) > 50:
                datasource = datasource[:47] + "..."
            canvas_obj.drawString(0.75 * inch, letter[1] - 0.5 * inch,
                                f"DHCaaS Report - {datasource}")
            
            canvas_obj.drawRightString(letter[0] - 0.75 * inch, letter[1] - 0.5 * inch,
                                     datetime.now().strftime('%B %d, %Y'))
            canvas_obj.restoreState()

        doc.build(
            story,
            onFirstPage=on_first_page,
            onLaterPages=on_later_pages,
            canvasmaker=DHCaaSReportCanvas
        )

        return output_path

