    def create_pie_chart(self, data_dict: Dict[str, float], title: str, 
                        chart_type: str = 'severity',
                        width: float = 4 * inch, height: float = 3 * inch) -> Drawing:
        """
        Create professional pie chart with EXPLICIT color assignment
        FIXED: No more gray monotone - colors are assigned directly by index
        
        Args:
            data_dict: Data to chart {label: value}
            title: Chart title
            chart_type: 'severity' or 'dimension' (determines color scheme)
            width: Chart width
            height: Chart height
        """
        drawing = Drawing(width, height)

        pie = Pie()
        pie.x = width / 2 - 100
        pie.y = height / 2 - 50
        pie.width = 180
        pie.height = 180

        pie.data = list(data_dict.values())
        
        # Create labels with percentages
        total = sum(data_dict.values())
        if total > 0:
            pie.labels = [f"{k}\n{(v/total*100):.1f}%" for k, v in data_dict.items()]
        else:
            pie.labels = list(data_dict.keys())

        # Slice styling
        pie.slices.strokeWidth = 2
        pie.slices.strokeColor = colors.white
        pie.slices.fontName = 'Helvetica-Bold'
        pie.slices.fontSize = 9
        pie.slices.fontColor = colors.HexColor('#1E293B')

        # ═══════════════════════════════════════════════════════════════
        # CRITICAL FIX: Direct color assignment by slice index
        # NO lookup, NO fallback to gray - explicit colors for each slice
        # ═══════════════════════════════════════════════════════════════
        
        if chart_type == 'dimension':
            # Quality Dimensions - BRIGHT DISTINCT COLORS (IN ORDER)
            color_sequence = [
                colors.HexColor('#1ABC9C'),  # Teal (Completeness)
                colors.HexColor('#3498DB'),  # Blue (Accuracy)
                colors.HexColor('#2C3E50'),  # Navy (Consistency)
                colors.HexColor('#95A5A6'),  # Gray (Validity)
            ]
        elif chart_type == 'severity':
            # Severity - RED/AMBER/BLUE/GREEN (IN ORDER)
            color_sequence = [
                colors.HexColor('#DC2626'),  # Red (Critical)
                colors.HexColor('#F59E0B'),  # Amber (High)
                colors.HexColor('#3B82F6'),  # Blue (Medium)
                colors.HexColor('#10B981'),  # Green (Low)
            ]
        else:
            # Default fallback
            color_sequence = [
                colors.HexColor('#3B82F6'),  # Blue
                colors.HexColor('#10B981'),  # Green
                colors.HexColor('#F59E0B'),  # Amber
                colors.HexColor('#DC2626'),  # Red
            ]

        # APPLY COLORS DIRECTLY TO EACH SLICE BY INDEX
        for i in range(len(pie.data)):
            # Use modulo to cycle through colors if more data than colors
            color_index = i % len(color_sequence)
            pie.slices[i].fillColor = color_sequence[color_index]
            
            # Enhanced label positioning
            pie.slices[i].labelRadius = 1.2
            pie.slices[i].fontColor = colors.HexColor('#1E293B')

        # Add title
        title_string = String(width / 2, height - 20, title, textAnchor='middle')
        title_string.fontName = 'Helvetica-Bold'
        title_string.fontSize = 14
        title_string.fillColor = self.colors['brand_secondary']

        drawing.add(pie)
        drawing.add(title_string)

        return drawing

