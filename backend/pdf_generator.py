class DHCaaSReportCanvas(canvas.Canvas):
    """Custom canvas with enterprise-grade footer on every page"""
    
    def __init__(self, *args, **kwargs):
        canvas.Canvas.__init__(self, *args, **kwargs)
        self.pages = []
        
    def showPage(self):
        self.pages.append(dict(self.__dict__))
        self._startPage()
        
    def save(self):
        page_count = len(self.pages)
        for page_num, page in enumerate(self.pages, 1):
            self.__dict__.update(page)
            self.draw_footer(page_num, page_count)
            canvas.Canvas.showPage(self)
        canvas.Canvas.save(self)
        
    def draw_footer(self, page_num, page_count):
        """Enterprise footer with copyright and confidentiality"""
        self.saveState()
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#64748b"))
        
        # Left: Copyright
        self.drawString(0.75 * inch, 0.5 * inch, "© 2026 DHCaaS Inc. All Rights Reserved.")
        
        # Right: Generated by + Page numbers
        right_text = f"Generated by DHCaaS Platform • CONFIDENTIAL • Page {page_num} of {page_count}"
        text_width = self.stringWidth(right_text, "Helvetica", 8)
        self.drawString(letter[0] - text_width - 0.75 * inch, 0.5 * inch, right_text)
        
        self.restoreState()


