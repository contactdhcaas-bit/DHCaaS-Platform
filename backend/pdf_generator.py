    def draw_tech_pattern(self, c, width, height):
        """Draw sophisticated tech connectivity pattern background"""
        c.saveState()
        c.setStrokeColor(colors.white)
        c.setStrokeAlpha(0.1)
        c.setLineWidth(0.5)
        
        # Diagonal lines pattern
        for i in range(0, int(width), 40):
            c.line(i, 0, i + height, height)
            
        for i in range(0, int(height), 40):
            c.line(0, i, width, i + width)
            
        # Connection nodes
        c.setFillColor(colors.white)
        c.setFillAlpha(0.15)
        for x in range(50, int(width), 80):
            for y in range(50, int(height), 80):
                c.circle(x, y, 3, fill=1, stroke=0)
                
        c.restoreState()
        
